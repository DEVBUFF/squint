#!/usr/bin/env bash
# Monthly squint trend research via headless Claude Code.
#   schedule.sh install [--day 1] [--hour 10]   macOS: launchd agent · Linux: user crontab
#   schedule.sh status | remove | run-now
# The job runs `claude -p "/squint:research"` with only research tools pre-approved and
# writes the personal trend base to ~/.squint/trends/<YYYY-MM>/ (logs in ~/.squint/logs/).
set -euo pipefail

LABEL="dev.squint.research"
AD_HOME="${SQUINT_HOME:-$HOME/.squint}"
PLUGIN_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUNNER="$AD_HOME/bin/run-research.sh"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
DAY=1
HOUR=10
ALLOWED="Read,Write,Edit,Glob,Grep,WebSearch,WebFetch,Agent,Bash(python3 *),mcp__plugin_squint_exa__web_search_exa,mcp__plugin_squint_exa__web_fetch_exa"

cmd="${1:-status}"
shift || true
while [ $# -gt 0 ]; do
  case "$1" in
    --day) DAY="$2"; shift 2 ;;
    --hour) HOUR="$2"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

write_runner() {
  local claude_bin
  claude_bin="$(command -v claude || true)"
  if [ -z "$claude_bin" ]; then
    echo "claude CLI not found on PATH" >&2
    exit 1
  fi
  mkdir -p "$AD_HOME/bin" "$AD_HOME/logs"
  cat > "$RUNNER" <<EOF
#!/usr/bin/env bash
# Generated by squint scripts/schedule.sh - monthly trend research.
export PATH="$(dirname "$claude_bin"):\$PATH:/opt/homebrew/bin:/usr/local/bin"
cd "$AD_HOME"
# the installed plugin directory changes on updates: pick the newest install, else the original path
PLUGIN_DIR="\$(ls -dt "\$HOME"/.claude/plugins/cache/*/squint/*/ 2>/dev/null | head -1)"
[ -n "\$PLUGIN_DIR" ] || PLUGIN_DIR="$PLUGIN_ROOT"
LOG="$AD_HOME/logs/research-\$(date +%Y-%m).log"
echo "=== \$(date) research run (plugin: \$PLUGIN_DIR)" >> "\$LOG"
"$claude_bin" -p "/squint:research" \\
  --permission-mode dontAsk \\
  --allowedTools "$ALLOWED" \\
  --add-dir "$AD_HOME" \\
  --add-dir "\$PLUGIN_DIR" \\
  >> "\$LOG" 2>&1
echo "=== exit \$? at \$(date)" >> "\$LOG"
EOF
  chmod +x "$RUNNER"
}

install_macos() {
  mkdir -p "$(dirname "$PLIST")"
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array><string>/bin/bash</string><string>-lc</string><string>$RUNNER</string></array>
  <key>StartCalendarInterval</key>
  <dict><key>Day</key><integer>$DAY</integer><key>Hour</key><integer>$HOUR</integer><key>Minute</key><integer>0</integer></dict>
  <key>StandardOutPath</key><string>$AD_HOME/logs/launchd.log</string>
  <key>StandardErrorPath</key><string>$AD_HOME/logs/launchd.log</string>
</dict>
</plist>
EOF
  launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$PLIST" 2>/dev/null || launchctl load -w "$PLIST"
  echo "installed launchd agent $LABEL: day $DAY of every month at $HOUR:00 (runs on wake if the Mac was asleep)"
}

install_cron() {
  local line="0 $HOUR $DAY * * /bin/bash -lc '$RUNNER' # $LABEL"
  ( crontab -l 2>/dev/null | grep -v "$LABEL" || true; echo "$line" ) | crontab -
  echo "installed cron job: $line"
}

case "$cmd" in
  install)
    write_runner
    if [ "$(uname)" = "Darwin" ]; then install_macos; else install_cron; fi
    echo "runner: $RUNNER"
    echo "logs:   $AD_HOME/logs/"
    ;;
  remove)
    if [ "$(uname)" = "Darwin" ]; then
      launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || launchctl unload "$PLIST" 2>/dev/null || true
      rm -f "$PLIST"
    else
      ( crontab -l 2>/dev/null | grep -v "$LABEL" || true ) | crontab -
    fi
    rm -f "$RUNNER"
    echo "removed monthly research schedule"
    ;;
  status)
    if [ "$(uname)" = "Darwin" ]; then
      if [ -f "$PLIST" ]; then
        echo "launchd agent installed: $PLIST"
        launchctl print "gui/$(id -u)/$LABEL" 2>/dev/null | grep -E "state|last exit" || true
      else
        echo "not scheduled"
      fi
    else
      crontab -l 2>/dev/null | grep "$LABEL" || echo "not scheduled"
    fi
    ls -t "$AD_HOME"/logs/research-*.log 2>/dev/null | head -1 | sed 's/^/latest log: /' || true
    ;;
  run-now)
    [ -x "$RUNNER" ] || write_runner
    nohup "$RUNNER" >/dev/null 2>&1 &
    echo "research started in the background (pid $!); log: $AD_HOME/logs/research-$(date +%Y-%m).log"
    ;;
  *)
    echo "usage: schedule.sh install [--day N] [--hour H] | status | remove | run-now" >&2
    exit 2
    ;;
esac
